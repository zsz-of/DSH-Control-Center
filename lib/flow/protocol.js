/**
 * 「对用户输出」协议 + 「先规划后执行」纪律。
 *
 * ⚠️ **这段文字每个模型请求都会进系统提示**（本项目实测：一个回合 26 步就有 26 次请求），
 * 所以它是本项目对 token 预算影响最大的地方，必须写得紧：只写可执行的规则，不写背景故事，
 * 也不重复界面已经表达的东西。`host.test.js` 有一条断言把长度锁在 {@link PROTOCOL_BUDGET} 以内，
 * 想加内容就得先删掉同量的内容。
 */
export const PROTOCOL_TEXT = `## 对话流协议

### 对用户输出：只在这四个时机
1. **任务开始时** —— 一句话说明要做什么。
2. **输出任务计划时** —— 只讲计划本身。
3. **需要审批或决定时** —— 用提问工具，别用正文代替。
4. **任务结束时** —— 先调 \`chat_flow_summary\`，再汇报结果、证据与遗留问题。

其余时机不写正文（会折进「正在处理」）：命令、工具、读写、检索都不写长文本；不写「现在我来…」这类旁白。

### 先规划，再执行
- 多步任务**第一步先写计划**：一次 \`todo_write\` 写出完整列表（每项一行祈使句）。
- 每完成一项立即重发整表（标 \`completed\`、下一项 \`in_progress\`），**禁止批量补记**。
- 只值一步的琐事不写计划，直接做完；列表即边界，不要复述。`

